// Builds the hero photos the site actually serves, from the originals in assets/images/hero-*.jpg.
// Run with `npm run hero-photos` after adding or replacing a hero photo, and commit what it writes.
//
// The site is a static export, so Next.js can't resize images on request: without this, every visitor
// downloads the full 2700px original (2–3 MB) even on a phone. For each photo this writes:
//   public/hero/<name>-<width>.avif and .jpg   six widths, so each browser downloads only the size it needs
//   lib/heroPhotos.ts                          their srcsets, plus a tiny blurred preview shown at once
// The hero always shows its photo in grayscale (see .lp-hero-photo), so the files are grayscale too: the
// colour data would never be seen.

import { mkdir, readdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const sourceDir = path.join(root, "assets/images");
const outDir = path.join(root, "public/hero");
const moduleFile = path.join(root, "lib/heroPhotos.ts");

const WIDTHS = [640, 960, 1280, 1600, 1920, 2400];
const AVIF = { quality: 50, effort: 6 };
const JPEG = { quality: 74, mozjpeg: true, progressive: true };

const files = (await readdir(sourceDir)).filter((file) => /^hero-.+\.jpe?g$/i.test(file)).sort();
await rm(outDir, { recursive: true, force: true });
await mkdir(outDir, { recursive: true });

const photos = {};
for (const file of files) {
  const name = path.basename(file, path.extname(file)).replace(/^hero-/, "");
  const source = sharp(path.join(sourceDir, file)).rotate().grayscale();
  const { width: fullWidth, height: fullHeight } = await source.clone().toBuffer({ resolveWithObject: true }).then((r) => r.info);
  const widths = WIDTHS.filter((w) => w < fullWidth).concat(Math.min(fullWidth, WIDTHS.at(-1)));
  const unique = [...new Set(widths)];

  let bytes = 0;
  for (const width of unique) {
    const resized = source.clone().resize({ width });
    const avif = await resized.clone().avif(AVIF).toBuffer();
    const jpeg = await resized.clone().jpeg(JPEG).toBuffer();
    await writeFile(path.join(outDir, `${name}-${width}.avif`), avif);
    await writeFile(path.join(outDir, `${name}-${width}.jpg`), jpeg);
    if (width === 1920) bytes = avif.length;
  }

  // A 32px-wide preview, inlined in the page so something shows before any image request finishes.
  const preview = await source.clone().resize({ width: 32 }).blur(0.6).webp({ quality: 40 }).toBuffer();

  photos[name] = {
    width: fullWidth,
    height: fullHeight,
    avif: unique.map((w) => `${name}-${w}.avif ${w}w`).join(", "),
    jpeg: unique.map((w) => `${name}-${w}.jpg ${w}w`).join(", "),
    fallback: `${name}-${unique.find((w) => w >= 1600) ?? unique.at(-1)}.jpg`,
    preview: `data:image/webp;base64,${preview.toString("base64")}`,
  };
  console.log(`${file}: ${unique.length} widths; 1920px AVIF is ${(bytes / 1024).toFixed(0)} KB`);
}

const header = `// Generated by scripts/make-hero-photos.mjs from assets/images/hero-*.jpg. Don't edit by hand:
// run \`npm run hero-photos\` after changing a hero photo. Paths are relative to public/hero/.

export type HeroPhotoSource = {
  width: number;
  height: number;
  /** srcset of grayscale AVIF files */
  avif: string;
  /** srcset of grayscale JPEG files, for browsers without AVIF */
  jpeg: string;
  /** the JPEG used as src */
  fallback: string;
  /** a tiny blurred WebP, as a data URL */
  preview: string;
};

export const HERO_PHOTOS = ${JSON.stringify(photos, null, 2)} as const satisfies Record<string, HeroPhotoSource>;
`;
await writeFile(moduleFile, header);
console.log(`Wrote ${path.relative(root, outDir)}/ and ${path.relative(root, moduleFile)}`);
